def _tab_terms():
    st.subheader("용어 사전")
    st.markdown("""
#### 기본 개념
| 용어 | 뜻 |
|---|---|
| **오토인코더(AE)** | 입력을 압축했다 복원하는 신경망. 정상만 학습시켜 "정상 복원기"로 씁니다 |
| **재구성 오차** | 입력과 복원 결과의 차이. **클수록 정상에서 멀다**는 뜻 |
| **임계값(threshold)** | 이 값을 넘으면 이상으로 판정하는 기준선 |
| **이상 점수** | 재구성 오차 ÷ 임계값. **1.0을 넘으면 이상** (2.0이면 기준의 2배) |
| **병목(bottleneck)** | AE가 정보를 압축하는 정도. 너무 크면 이상까지 잘 복원해 **탐지가 약해집니다** |

#### 데이터·학습
| 용어 | 뜻 |
|---|---|
| **정규화(스케일링)** | 센서마다 단위가 달라(℃ vs rpm) 크기를 맞추는 처리. 학습 시 기준을 저장해 판정에도 그대로 씁니다 |
| **보정용(calibration) 데이터** | 학습에 쓰지 않고 남겨둔 정상 데이터. **임계값 산출 전용**입니다 |
| **epoch** | 학습 반복 횟수. 손실이 더 안 줄면 자동으로 멈춥니다(조기 종료) |
| **Dense AE / LSTM-AE** | 행 단위 모델 / 시계열 구간 모델. 시간 의존성이 높으면 LSTM이 유리합니다 |
| **시간 의존성(자기상관)** | 값이 시간에 걸쳐 이어지는 정도. 높으면 시계열 모델을 권장합니다 |

#### 평가 지표
| 용어 | 뜻 |
|---|---|
| **Precision(정밀도)** | 이상이라고 한 것 중 진짜 이상 비율. 낮으면 **헛알람이 많음** |
| **Recall(재현율)** | 실제 이상 중 잡아낸 비율. 낮으면 **놓친 게 많음** |
| **F1** | 정밀도와 재현율의 균형 점수(0~1). 높을수록 좋음 |
| **PR-AUC** | 불균형 데이터에서 신뢰도 높은 종합 성능 지표 |
| **오경보율(FAR)** | 정상인데 이상이라 한 비율. **현장 신뢰도와 직결** |
| **에피소드 검출률** | 이상 **구간**을 하나라도 잡아낸 비율. 샘플 F1보다 현장에 가깝습니다 |
| **탐지 지연** | 이상 시작 후 몇 샘플 만에 잡았는지. 짧을수록 조기 경보 가치가 큼 |

#### 모니터링
| 용어 | 뜻 |
|---|---|
| **드리프트** | 설비·환경이 변해 정상 패턴 자체가 이동하는 현상. 방치하면 오탐/미탐이 늘어납니다 |
| **z-score** | 현재 평균 오차가 학습 기준에서 몇 σ 벗어났는지 |
| **PSI** | 분포 이동 정도. 0.1↑ 주의, 0.25↑ 경고 |
| **KS 검정** | 두 분포가 통계적으로 다른지 검정(p<0.05면 다름) |
| **알람 디바운싱(K/M)** | 최근 M건 중 K건 이상일 때만 알람. 산발적 헛알람을 걸러냅니다 |
""")


def _tab_interpret():
    st.subheader("결과를 어떻게 읽나요?")
